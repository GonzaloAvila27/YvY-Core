"""Embed version info from git into yvy_server/_version.py.

This script runs at build time (called from Dockerfile or manually).
It generates `src/yvy_server/_version.py` with the current git commit hash
and build timestamp, so the running server can report exactly which
revision is deployed.

Two modes:

1. **Local dev / CI with git access:** runs `git rev-parse` to get the
   commit hash. Computes UTC timestamp at runtime.

2. **Build mode (no git available inside the container):** the caller
   sets env vars ``YVY_BUILD_GIT_COMMIT``, ``YVY_BUILD_GIT_COMMIT_SHORT``
   and ``YVY_BUILD_DATE``. The script uses those instead of running git.
   This lets the Dockerfile avoid copying ``.git`` into the build context.

The generated file is gitignored. If neither mode yields a value, the
fallback in ``__init__.py`` takes effect (`"unknown"`).

Usage:
    # Mode 1 (dev with git):
    python scripts/embed_version.py

    # Mode 2 (CI/Docker, no git in container):
    YVY_BUILD_GIT_COMMIT=$(git rev-parse HEAD) \\
    YVY_BUILD_GIT_COMMIT_SHORT=$(git rev-parse --short HEAD) \\
    YVY_BUILD_DATE=$(date -u +"%Y-%m-%dT%H:%M:%SZ") \\
        python scripts/embed_version.py

See `YVY_FASE9_Arquitectura_v2.md` §11.9 — visible code versioning.
"""

from __future__ import annotations

import datetime as _dt
import os
import re
import subprocess
import sys
from pathlib import Path

# ── Constants ────────────────────────────────────────────────────────────
REPO_ROOT = Path(__file__).resolve().parent.parent
PYPROJECT = REPO_ROOT / "pyproject.toml"
VERSION_FILE = REPO_ROOT / "src" / "yvy_server" / "_version.py"

DEFAULT_VERSION = "0.9.1-dev"
UNKNOWN = "unknown"

# Env var overrides for build mode (no git available in container)
ENV_GIT_COMMIT = "YVY_BUILD_GIT_COMMIT"
ENV_GIT_COMMIT_SHORT = "YVY_BUILD_GIT_COMMIT_SHORT"
ENV_BUILD_DATE = "YVY_BUILD_DATE"


def _read_base_version() -> str:
    """Read the [tool.poetry] version from pyproject.toml.

    We intentionally don't use tomllib for the read (would force python>=3.11
    in a script that should be runnable in older builders too). A simple
    regex is enough for this single field.
    """
    if not PYPROJECT.exists():
        return DEFAULT_VERSION
    text = PYPROJECT.read_text(encoding="utf-8")
    # Match: version = "0.9.1-dev"
    match = re.search(
        r'^\s*version\s*=\s*"([^"]+)"',
        text,
        flags=re.MULTILINE,
    )
    return match.group(1) if match else DEFAULT_VERSION


def _git(*args: str) -> str | None:
    """Run a git command and return stripped stdout, or None on any failure."""
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            check=True,
            timeout=5,
        )
        return result.stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError, subprocess.TimeoutExpired):
        return None


def _resolve_commit() -> tuple[str, str]:
    """Resolve (full_hash, short_hash) honoring env-var overrides first.

    Order of resolution:
        1. Env vars (build mode).
        2. ``git rev-parse`` (dev mode).
        3. ``("unknown", "unknown")`` fallback.
    """
    env_full = os.environ.get(ENV_GIT_COMMIT, "").strip()
    env_short = os.environ.get(ENV_GIT_COMMIT_SHORT, "").strip()
    if env_full and env_short:
        return env_full, env_short

    full = _git("rev-parse", "HEAD") or UNKNOWN
    short = _git("rev-parse", "--short", "HEAD") or UNKNOWN
    return full, short


def _resolve_build_date() -> str:
    """Resolve ISO 8601 UTC build date, honoring env-var override first."""
    env_date = os.environ.get(ENV_BUILD_DATE, "").strip()
    if env_date:
        return env_date
    return _dt.datetime.now(_dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _git_dirty_suffix() -> str:
    """Return '+dirty' if working tree has uncommitted changes, else ''.

    Skipped in build mode (env-var path) since the env vars are presumed
    authoritative.
    """
    if os.environ.get(ENV_GIT_COMMIT):
        return ""
    status = _git("status", "--porcelain")
    if status is None:
        return ""
    return "+dirty" if status else ""


def main() -> int:
    base_version = _read_base_version()
    commit_full, commit_short = _resolve_commit()
    dirty = _git_dirty_suffix()
    build_date = _resolve_build_date()

    # Visible version: base + commit short + dirty flag.
    # Examples: "0.9.1-dev+a7b8c9d" or "0.9.1-dev+a7b8c9d+dirty"
    if commit_short != UNKNOWN:
        visible_version = f"{base_version}+{commit_short}{dirty}"
    else:
        visible_version = f"{base_version}+{UNKNOWN}"

    content = f'''"""Auto-generated version info. DO NOT EDIT.

Generated by scripts/embed_version.py at build time.
This file is gitignored — never commit it.
"""

__version__ = "{visible_version}"
__version_base__ = "{base_version}"
__git_commit__ = "{commit_full}"
__git_commit_short__ = "{commit_short}"
__build_date__ = "{build_date}"
'''

    VERSION_FILE.parent.mkdir(parents=True, exist_ok=True)
    VERSION_FILE.write_text(content, encoding="utf-8")

    print(f"Wrote {VERSION_FILE.relative_to(REPO_ROOT)}")
    print(f"  __version__      = {visible_version}")
    print(f"  __git_commit__   = {commit_full}")
    print(f"  __build_date__   = {build_date}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
